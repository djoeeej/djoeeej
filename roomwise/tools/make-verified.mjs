// Turns a link-check report into js/verified.js, which the app reads to show when each
// product link was last opened and what price the store showed.
//
//   node make-verified.mjs link-report.json      the JSON written by check-links.mjs --json
//   node make-verified.mjs job-log.txt           or a saved GitHub Actions log (JSON lines)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Several reports can be given, oldest first: a later OK or MOVED replaces an earlier result,
// but a later BLOCKED never hides an earlier successful check.
const links = {};
let checked = null;
const RANK = { OK: 3, MOVED: 2, BROKEN: 2, BLOCKED: 1 };
for (const file of process.argv.slice(2)) {
  const src = readFileSync(file, 'utf8');
  let results;
  try {
    const j = JSON.parse(src);
    if (j.results) { results = j.results; checked = j.checked ?? checked; } else throw new Error('not a report');
  } catch {
    const text = (() => { try { return JSON.parse(src).logs_content; } catch { return src; } })();
    results = [...text.matchAll(/JSON (\{.*\})\s*$/gm)].map((m) => JSON.parse(m[1]));
    checked = text.match(/^\uFEFF?(\d{4}-\d\d-\d\d)T/m)?.[1] ?? checked;
  }
  for (const r of results) {
    // Only trust prices from the page's product data (e.g. "USD 169"), not the first $ on the page.
    const price = typeof r.price === 'string' && /^[A-Z]{3} /.test(r.price) ? +r.price.replace(/[^\d.]/g, '') : null;
    const prev = links[r.url];
    if (prev && RANK[r.result] < RANK[prev.r] && r.result === 'BLOCKED') continue;
    links[r.url] = { r: r.result, ...(price > 0 ? { p: price } : prev?.p && r.result === 'BLOCKED' ? { p: prev.p } : {}) };
  }
}
// Keep only links the catalog still uses.
const { allLinks, PAINT } = await import('../js/catalog.js');
void PAINT;
const used = new Set(allLinks().map((l) => l.url));
for (const url of Object.keys(links)) if (!used.has(url)) delete links[url];
const results = Object.values(links).map((l) => ({ result: l.r }));
const out = `// Generated by tools/make-verified.mjs from the product link checker. Do not edit by hand.
// r: OK (the page opened and showed the product), BLOCKED (the store stops automated browsers;
// the link comes from the store's own search listing), MOVED or BROKEN. p: the price shown, USD.
export const VERIFIED = ${JSON.stringify({ checked: (checked ?? new Date().toISOString()).slice(0, 10), links }, null, 1)};
`;
const dest = fileURLToPath(new URL('../js/verified.js', import.meta.url));
writeFileSync(dest, out);
const count = (k) => results.filter((r) => r.result === k).length;
console.log(`wrote ${dest}: ${results.length} links, ok=${count('OK')} blocked=${count('BLOCKED')} moved=${count('MOVED')} broken=${count('BROKEN')}`);
